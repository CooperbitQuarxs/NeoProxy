// Command gen writes cursor_proto.gen.go from gen/cursor_proto.json, the
// message descriptors exported from NeoPi's generated cursor-proto.ts by
// gen/export_cursor_proto.ts. Each message becomes a Go struct with Marshal
// and Unmarshal methods that follow NeoPi's protobuf.ts codec. Run it from
// internal/cursorwire (go generate).
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
)

type field struct {
	Kind     string    `json:"kind"`
	No       int32     `json:"no"`
	Name     string    `json:"name"`
	Message  string    `json:"message"`
	Repeat   bool      `json:"repeat"`
	Optional bool      `json:"optional"`
	Variants []field   `json:"variants"`
	Key      string    `json:"key"`
	Value    *mapValue `json:"value"`
}

type mapValue struct {
	Scalar  string `json:"scalar"`
	Message string `json:"message"`
}

type message struct {
	Name     string  `json:"name"`
	TypeName string  `json:"typeName"`
	Fields   []field `json:"fields"`
}

type scalarInfo struct {
	goType   string
	wire     string
	isZero   string // expression over v that is true at NeoPi's default
	appendFn string // expression appending v to b
	readFn   string // reader method
}

var scalars = map[string]scalarInfo{
	"bool":   {"bool", "wireVarint", "!v", "appendBool(b, v)", "bool"},
	"bytes":  {"[]byte", "wireBytes", "len(v) == 0", "appendLengthDelimited(b, v)", "bytes"},
	"double": {"float64", "wireFixed64", "v == 0", "appendDouble(b, v)", "double"},
	"float":  {"float32", "wireFixed32", "v == 0", "appendFloat(b, v)", "float"},
	"enum":   {"int32", "wireVarint", "v == 0", "appendInt32(b, v)", "int32"},
	"int32":  {"int32", "wireVarint", "v == 0", "appendInt32(b, v)", "int32"},
	"int64":  {"int64", "wireVarint", "v == 0", "appendVarint(b, uint64(v))", "int64"},
	"string": {"string", "wireBytes", `v == ""`, "appendLengthDelimited(b, []byte(v))", "string"},
	"uint32": {"uint32", "wireVarint", "v == 0", "appendVarint(b, uint64(v))", "uint32"},
	"uint64": {"uint64", "wireVarint", "v == 0", "appendVarint(b, v)", "uint64"},
}

func pascal(name string) string {
	if name == "" {
		return name
	}
	return strings.ToUpper(name[:1]) + name[1:]
}

type generator struct {
	out      bytes.Buffer
	messages map[string]bool
	wrappers map[string]string // message.oneofName.variant -> Go wrapper type
	taken    map[string]bool
}

func (g *generator) p(format string, args ...any) {
	fmt.Fprintf(&g.out, format, args...)
	g.out.WriteByte('\n')
}

func (g *generator) unique(name string) string {
	for g.taken[name] {
		name += "_"
	}
	g.taken[name] = true
	return name
}

func main() {
	data, err := os.ReadFile(filepath.Join("gen", "cursor_proto.json"))
	if err != nil {
		fail(err)
	}
	var doc struct {
		Source   string    `json:"source"`
		Messages []message `json:"messages"`
	}
	if err = json.Unmarshal(data, &doc); err != nil {
		fail(err)
	}
	g := &generator{messages: map[string]bool{}, wrappers: map[string]string{}, taken: map[string]bool{}}
	for _, m := range doc.Messages {
		g.messages[m.Name] = true
		g.taken[m.Name] = true
	}
	for _, m := range doc.Messages {
		for _, f := range m.Fields {
			if f.Kind != "oneof" {
				continue
			}
			g.taken["is"+m.Name+"_"+pascal(f.Name)] = true
			for _, v := range f.Variants {
				g.wrappers[m.Name+"."+f.Name+"."+v.Name] = g.unique(m.Name + "_" + pascal(v.Name))
			}
		}
	}

	g.p("// Code generated by internal/cursorwire/gen from cursor_proto.json; DO NOT EDIT.")
	g.p("// Source: %s", doc.Source)
	g.p("")
	g.p("package cursorwire")
	for _, m := range doc.Messages {
		g.message(m)
	}
	formatted, err := format.Source(g.out.Bytes())
	if err != nil {
		_ = os.WriteFile("cursor_proto.gen.go.broken", g.out.Bytes(), 0o644)
		fail(err)
	}
	if err = os.WriteFile("cursor_proto.gen.go", formatted, 0o644); err != nil {
		fail(err)
	}
	var registry bytes.Buffer
	registry.WriteString("// Code generated by internal/cursorwire/gen from cursor_proto.json; DO NOT EDIT.\n\npackage cursorwire\n\n")
	registry.WriteString("// generatedMessages constructs every generated message by its NeoPi name.\nvar generatedMessages = map[string]func() interface {\n\tMarshal() []byte\n\tUnmarshal([]byte) error\n}{\n")
	for _, m := range doc.Messages {
		fmt.Fprintf(&registry, "\t%q: func() interface {\n\t\tMarshal() []byte\n\t\tUnmarshal([]byte) error\n\t} {\n\t\treturn &%s{}\n\t},\n", m.Name, m.Name)
	}
	registry.WriteString("}\n")
	formattedRegistry, err := format.Source(registry.Bytes())
	if err != nil {
		fail(err)
	}
	if err = os.WriteFile("cursor_proto_registry_gen_test.go", formattedRegistry, 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}

func (g *generator) goType(f field) string {
	switch f.Kind {
	case "message":
		if f.Repeat {
			return "[]*" + f.Message
		}
		return "*" + f.Message
	case "map":
		if f.Value.Message != "" {
			return "Map[*" + f.Value.Message + "]"
		}
		return "Map[" + scalars[f.Value.Scalar].goType + "]"
	}
	t := scalars[f.Kind].goType
	switch {
	case f.Repeat:
		return "[]" + t
	case f.Optional:
		return "*" + t
	}
	return t
}

func (g *generator) message(m message) {
	g.p("")
	g.p("// %s is %s.", m.Name, m.TypeName)
	g.p("type %s struct {", m.Name)
	for _, f := range m.Fields {
		if f.Kind == "oneof" {
			g.p("%s is%s_%s", pascal(f.Name), m.Name, pascal(f.Name))
			continue
		}
		g.p("%s %s", pascal(f.Name), g.goType(f))
	}
	g.p("// Unknown holds fields the declarations do not model, re-emitted last.")
	g.p("Unknown []byte")
	g.p("}")

	for _, f := range m.Fields {
		if f.Kind != "oneof" {
			continue
		}
		iface := "is" + m.Name + "_" + pascal(f.Name)
		g.p("")
		g.p("type %s interface{ %s() }", iface, iface)
		for _, v := range f.Variants {
			wrapper := g.wrappers[m.Name+"."+f.Name+"."+v.Name]
			valueType := "*" + v.Message
			if v.Kind != "message" {
				valueType = scalars[v.Kind].goType
			}
			g.p("")
			g.p("// %s selects %s.%s (field %d).", wrapper, m.Name, f.Name, v.No)
			g.p("type %s struct{ %s %s }", wrapper, pascal(v.Name), valueType)
			g.p("func (*%s) %s() {}", wrapper, iface)
		}
	}

	g.p("")
	g.p("// Marshal encodes the message as NeoPi does.")
	g.p("func (m *%s) Marshal() []byte { return m.appendTo(nil) }", m.Name)
	g.p("")
	g.p("func (m *%s) appendTo(b []byte) []byte {", m.Name)
	g.p("if m == nil { return b }")
	for _, f := range m.Fields {
		g.encodeField(m, f)
	}
	g.p("return append(b, m.Unknown...)")
	g.p("}")

	g.p("")
	g.p("// Unmarshal decodes data as NeoPi does, replacing the message.")
	g.p("func (m *%s) Unmarshal(data []byte) error {", m.Name)
	g.p("*m = %s{}", m.Name)
	g.p("r := reader{buf: data}")
	g.p("for r.more() {")
	g.p("number, wireType, err := r.tag()")
	g.p("if err != nil { return err }")
	g.p("switch number {")
	for _, f := range m.Fields {
		g.decodeField(m, f)
	}
	g.p("default:")
	g.p("if err = r.unknown(&m.Unknown, number, wireType); err != nil { return err }")
	g.p("}")
	g.p("}")
	g.p("return nil")
	g.p("}")
}

func (g *generator) encodeField(m message, f field) {
	name := "m." + pascal(f.Name)
	switch f.Kind {
	case "oneof":
		g.p("switch o := %s.(type) {", name)
		for _, v := range f.Variants {
			wrapper := g.wrappers[m.Name+"."+f.Name+"."+v.Name]
			g.p("case *%s:", wrapper)
			value := "o." + pascal(v.Name)
			if v.Kind == "message" {
				g.p("if %s != nil {", value)
				g.p("b = appendTag(b, %d, wireBytes)", v.No)
				g.p("b = appendLengthDelimited(b, %s.Marshal())", value)
				g.p("}")
				continue
			}
			s := scalars[v.Kind]
			g.p("b = appendTag(b, %d, %s)", v.No, s.wire)
			g.p("{ v := %s; b = %s }", value, s.appendFn)
		}
		g.p("}")
	case "message":
		if f.Repeat {
			g.p("for _, v := range %s {", name)
			g.p("b = appendTag(b, %d, wireBytes)", f.No)
			g.p("b = appendLengthDelimited(b, v.Marshal())")
			g.p("}")
			return
		}
		g.p("if %s != nil {", name)
		g.p("b = appendTag(b, %d, wireBytes)", f.No)
		g.p("b = appendLengthDelimited(b, %s.Marshal())", name)
		g.p("}")
	case "map":
		g.p("for _, k := range %s.Keys() {", name)
		g.p("v, _ := %s.Get(k)", name)
		g.p("var entry []byte")
		g.p(`if k != "" { entry = appendTag(entry, 1, wireBytes); entry = appendLengthDelimited(entry, []byte(k)) }`)
		if f.Value.Message != "" {
			g.p("if v != nil { entry = appendTag(entry, 2, wireBytes); entry = appendLengthDelimited(entry, v.Marshal()) }")
		} else {
			s := scalars[f.Value.Scalar]
			g.p("if !(%s) { entry = appendTag(entry, 2, %s); entry = %s }", s.isZero, s.wire, strings.Replace(s.appendFn, "(b,", "(entry,", 1))
		}
		g.p("b = appendMapEntry(b, %d, entry)", f.No)
		g.p("}")
	default:
		s := scalars[f.Kind]
		switch {
		case f.Repeat && s.wire != "wireBytes":
			g.p("if len(%s) > 0 {", name)
			g.p("var packed []byte")
			g.p("for _, v := range %s { packed = %s }", name, strings.Replace(s.appendFn, "(b,", "(packed,", 1))
			g.p("b = appendTag(b, %d, wireBytes)", f.No)
			g.p("b = appendLengthDelimited(b, packed)")
			g.p("}")
		case f.Repeat:
			g.p("for _, v := range %s {", name)
			g.p("b = appendTag(b, %d, %s)", f.No, s.wire)
			g.p("b = %s", s.appendFn)
			g.p("}")
		case f.Optional:
			g.p("if %s != nil {", name)
			g.p("v := *%s", name)
			g.p("b = appendTag(b, %d, %s)", f.No, s.wire)
			g.p("b = %s", s.appendFn)
			g.p("}")
		default:
			g.p("if v := %s; !(%s) {", name, s.isZero)
			g.p("b = appendTag(b, %d, %s)", f.No, s.wire)
			g.p("b = %s", s.appendFn)
			g.p("}")
		}
	}
}

func (g *generator) decodeField(m message, f field) {
	name := "m." + pascal(f.Name)
	if f.Kind == "oneof" {
		for _, v := range f.Variants {
			wrapper := g.wrappers[m.Name+"."+f.Name+"."+v.Name]
			g.p("case %d:", v.No)
			if v.Kind == "message" {
				g.p("if err = expectWire(wireType, wireBytes); err != nil { return err }")
				g.p("data, err := r.bytes()")
				g.p("if err != nil { return err }")
				g.p("v := &%s{}", v.Message)
				g.p("if err = v.Unmarshal(data); err != nil { return err }")
				g.p("%s = &%s{%s: v}", name, wrapper, pascal(v.Name))
				continue
			}
			s := scalars[v.Kind]
			g.p("if err = expectWire(wireType, %s); err != nil { return err }", s.wire)
			g.p("v, err := r.%s()", s.readFn)
			g.p("if err != nil { return err }")
			g.p("%s = &%s{%s: v}", name, wrapper, pascal(v.Name))
		}
		return
	}
	g.p("case %d:", f.No)
	switch f.Kind {
	case "message":
		g.p("if err = expectWire(wireType, wireBytes); err != nil { return err }")
		g.p("data, err := r.bytes()")
		g.p("if err != nil { return err }")
		g.p("v := &%s{}", f.Message)
		g.p("if err = v.Unmarshal(data); err != nil { return err }")
		if f.Repeat {
			g.p("%s = append(%s, v)", name, name)
		} else {
			g.p("%s = v", name)
		}
	case "map":
		g.p("if err = expectWire(wireType, wireBytes); err != nil { return err }")
		g.p("data, err := r.bytes()")
		g.p("if err != nil { return err }")
		if f.Value.Message != "" {
			g.p("var value *%s", f.Value.Message)
			g.p("key, err := readMapEntry(data, func(e *reader, wireType int) error {")
			g.p("if err := expectWire(wireType, wireBytes); err != nil { return err }")
			g.p("data, err := e.bytes()")
			g.p("if err != nil { return err }")
			g.p("value = &%s{}", f.Value.Message)
			g.p("return value.Unmarshal(data)")
			g.p("})")
		} else {
			s := scalars[f.Value.Scalar]
			g.p("var value %s", s.goType)
			g.p("key, err := readMapEntry(data, func(e *reader, wireType int) error {")
			g.p("if err := expectWire(wireType, %s); err != nil { return err }", s.wire)
			g.p("v, err := e.%s()", s.readFn)
			g.p("value = v")
			g.p("return err")
			g.p("})")
		}
		g.p("if err != nil { return err }")
		g.p("%s.Set(key, value)", name)
	default:
		s := scalars[f.Kind]
		switch {
		case f.Repeat && s.wire != "wireBytes":
			g.p("isPacked, err := packed(wireType, %s)", s.wire)
			g.p("if err != nil { return err }")
			g.p("if isPacked {")
			g.p("data, err := r.bytes()")
			g.p("if err != nil { return err }")
			g.p("p := reader{buf: data}")
			g.p("for p.more() {")
			g.p("v, err := p.%s()", s.readFn)
			g.p("if err != nil { return err }")
			g.p("%s = append(%s, v)", name, name)
			g.p("}")
			g.p("} else {")
			g.p("v, err := r.%s()", s.readFn)
			g.p("if err != nil { return err }")
			g.p("%s = append(%s, v)", name, name)
			g.p("}")
		case f.Repeat:
			g.p("if err = expectWire(wireType, %s); err != nil { return err }", s.wire)
			g.p("v, err := r.%s()", s.readFn)
			g.p("if err != nil { return err }")
			g.p("%s = append(%s, v)", name, name)
		case f.Optional:
			g.p("if err = expectWire(wireType, %s); err != nil { return err }", s.wire)
			g.p("v, err := r.%s()", s.readFn)
			g.p("if err != nil { return err }")
			g.p("%s = &v", name)
		default:
			g.p("if err = expectWire(wireType, %s); err != nil { return err }", s.wire)
			g.p("v, err := r.%s()", s.readFn)
			g.p("if err != nil { return err }")
			g.p("%s = v", name)
		}
	}
}
